"""Generate small website assets without changing the original photos.

Run after replacing source images: python scripts/optimize_images.py
Requires Pillow with WebP support (builds on Vercel use committed output).
"""
from hashlib import sha256
import json
from pathlib import Path
import re

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
OUTPUT = PUBLIC / 'images/optimized'
OUTPUT.mkdir(parents=True, exist_ok=True)
manifest = {}
original_bytes = 0
full_bytes = 0
card_bytes = 0

for source in ['artistCardImages.ts', 'linkPreviews.ts']:
    text = (ROOT / 'src/data' / source).read_text(encoding='utf-8')
    for url in sorted(set(re.findall(r'"(/images/[^"\n]+)"', text))):
        path = PUBLIC / url.lstrip('/')
        is_portrait = source == 'artistCardImages.ts'
        original_bytes += path.stat().st_size
        # Content-based names let updated photos bypass an older browser cache.
        digest = sha256(path.read_bytes() + b'webp-v1-600q82-960q84-1280q86').hexdigest()[:12]
        with Image.open(path) as original:
            image = ImageOps.exif_transpose(original).convert('RGB')
            variants = [('src', 960, 84), ('card', 600, 82)] if is_portrait else [('src', 1280, 86)]
            entry = {}
            for key, size, quality in variants:
                resized = image.copy()
                resized.thumbnail((size, size), Image.Resampling.LANCZOS)
                filename = f'{path.stem}-{digest}-{size}.webp'
                destination = OUTPUT / filename
                resized.save(destination, 'WEBP', quality=quality, method=6)
                entry[key] = '/images/optimized/' + filename
                if key == 'card':
                    card_bytes += destination.stat().st_size
                else:
                    full_bytes += destination.stat().st_size
        manifest[url] = entry

target = ROOT / 'src/data/optimizedImages.ts'
target.write_text(
    '// Generated by scripts/optimize_images.py. Keep the source images unchanged.\n'
    'export const optimizedImages: Readonly<Record<string, { src: string; card?: string }>> = '
    + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(f'{len(manifest)} source images: {original_bytes / 1048576:.2f} MiB')
print(f'All full-size web images: {full_bytes / 1048576:.2f} MiB')
print(f'All 20 homepage thumbnails: {card_bytes / 1024:.0f} KiB')
